// ระบบไม่ควรผูกกับธนาคารเดียวตลอดไป แต่ก็ไม่ควร "เดา" รูปแบบเอกสารที่ไม่รู้จัก
// การเดาตารางใน PDF พลาดแบบเงียบ ๆ ได้ และตัวเลขบัญชีที่ผิดโดยไม่มีใครรู้ แย่กว่า
// การอ่านไม่ออกไปเลย
//
// ทางสายกลางคือทะเบียนนี้: แต่ละธนาคารบอกเองว่าจะดูออกได้ยังไง (detect) และอ่าน
// ยังไง (parse) ตัวอ่านกลางเลือกให้ตัวเดียว แล้วบังคับให้ผลลัพธ์ผ่าน **ยอดคุม**
// เหมือนกันหมด — ยอดยกมา + ฝาก − ถอน ต้องเท่ากับยอดยกไปที่ธนาคารพิมพ์ไว้
//
// ยอดคุมคือเหตุผลที่การเพิ่มธนาคารในระบบนี้ปลอดภัย adapter ที่อ่านคอลัมน์เพี้ยน
// หรือตกบรรทัดจะทำให้ยอดไม่ลงตัว แล้วไฟล์ถูกปฏิเสธ ไม่ใช่ถูกรับไว้เงียบ ๆ

export const BANKS = [kbank];

/** ธนาคารที่อ่านเอกสารนี้ได้ — ต้องมีตัวเดียวเท่านั้น */
export function detectBank(allLines) {
  const matches = BANKS.filter((bank) => bank.detect(allLines));
  if (matches.length === 1) return matches[0];
  // ไม่มีเลย = ไม่รู้จัก · มากกว่าหนึ่ง = คลุมเครือ ทั้งคู่ต้องไม่เดา
  return null;
}

export const bankLabels = () => BANKS.map((bank) => bank.label).join(" · ");
